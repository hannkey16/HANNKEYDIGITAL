// ─── helpers ────────────────────────────────────────────────────────────────

function plans(m1: number, m3: number, m6: number, yr: number, pop: 0 | 1 | 2 | 3 = 0): Plan[] {
  const mult = [1.8, 1.7, 1.6, 1.5]
  return [
    { name: '1 Bulan',  duration: '30 Hari',  price: m1,  originalPrice: Math.round(m1 * mult[0] / 500) * 500, popular: pop === 0 },
    { name: '3 Bulan',  duration: '90 Hari',  price: m3,  originalPrice: Math.round(m3 * mult[1] / 500) * 500, popular: pop === 1 },
    { name: '6 Bulan',  duration: '180 Hari', price: m6,  originalPrice: Math.round(m6 * mult[2] / 500) * 500, popular: pop === 2 },
    { name: '1 Tahun',  duration: '365 Hari', price: yr,  originalPrice: Math.round(yr  * mult[3] / 500) * 500, popular: pop === 3 },
  ]
}

