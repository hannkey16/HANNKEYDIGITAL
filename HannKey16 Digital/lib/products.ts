// ─── Lookup helpers ──────────────────────────────────────────────────────────

export const catalogBySlug = Object.fromEntries(catalog.map(p => [p.slug, p]))

export function getProductBySlug(slug: string): CatalogProduct | null {
  return catalogBySlug[slug] ?? null
}

export const CATEGORIES: ProductCategory[] = [
  'AI Tools', 'Design', 'Streaming', 'Music', 'Learning',
  'Cloud', 'VPN & Security', 'Developer', 'Communication', 'Gaming', 'Business',
]

export function getProductsByCategory(cat: ProductCategory): CatalogProduct[] {
  return catalog.filter(p => p.category === cat)
}

export function getRelatedProducts(slug: string, limit = 4): CatalogProduct[] {
  const product = catalogBySlug[slug]
  if (!product) return []
  return product.relatedSlugs
    .map(s => catalogBySlug[s])
    .filter(Boolean)
    .slice(0, limit) as CatalogProduct[]
}

export function formatRupiah(value: number): string {
  return `Rp ${value.toLocaleString('id-ID')}`
}
